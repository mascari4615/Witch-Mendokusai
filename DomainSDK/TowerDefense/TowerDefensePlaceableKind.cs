namespace WitchMendokusai
{
	/// <summary>
	/// 개척에서 설치할 수 있는 것의 종류 — 핫바 슬롯 1개당 하나 (TASK-WM-194).
	///
	/// 좌클릭=포탑 / 우클릭=채집 처럼 *버튼에 종류를 박는* 방식은 종류가 3개를 넘는 순간 못 늘린다
	/// (사용자 지시: "좌클릭/우클릭이 아니라 빌딩 핫바 좀 활용해야 할듯").
	/// 선택은 핫바가, 설치는 클릭이 맡는 문법이라 종류가 늘어도 슬롯만 늘면 된다.
	/// 가챠로 방어 인형이 늘어나는 방향(game-in-game-hub.md)과도 정합.
	/// </summary>
	public enum TowerDefensePlaceableKind
	{
		Tower = 0,     // 방어 인형 — 사거리 내 적을 쏜다.
		Harvester = 1, // 채집 인형 — 자원 노드 위에만, 수입 증가.
		Outpost = 5,   // 전초기지 — 새 보급 원점이자 *새 유출 지점*. 넓히면 벌지만 지킬 곳이 하나 는다.
		Trap = 4,      // 함정 — 바닥에 깐다. 밟으면 터지고 횟수를 다 쓰면 사라지는 소모품.
		Wall = 3,      // 벽 — 못 지나간다. 길 자체를 내가 그리는 수단(단, 완전히 막을 수는 없다).
		// 2 번은 옛 「연구 인형」 자리 — 연구는 코어를 골라서 하는 일이 되었다(짓는 것과 키우는 것은 다른 행위다).
		//   번호를 당기지 않는다: 저장된 판이 들고 있는 숫자의 뜻이 통째로 밀린다.
		Hero = 6,      // 영웅 인형 — 유일하게 *짓는 게 아니라 보내는* 칸. 클릭한 자리로 걸어간다(비용 0).
		Generator = 7, // 발전 인형 — 범위 안 건물에 전기를 댄다. 이게 없으면 방어를 늘릴 수 없다.
	}
}
