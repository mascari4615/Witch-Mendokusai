namespace WitchMendokusai
{
	/// <summary>
	/// 설치 입력 모드 — "버튼을 누르고 있는 동안 어떻게 설치되는가"의 정책 (TASK-WM-194).
	///
	/// 사용자 발화: "기존 빌딩이 연속해서 입력 받게 만들어져 있어서 드래그가 된다.
	/// 여기에서는 한 클릭에 한 개만 설치할 수 있어야 해. 기존 빌딩에 설치 입력 모드 같은거 만들어서 확장하자."
	///
	/// 두 모드는 각각 옳다 — 월드 건설(BuildManager)은 벽·바닥을 죽 긋는 드래그가 자연스럽고,
	/// 개척(TD)은 비용이 붙는 유닛을 한 기씩 놓는 게임이라 드래그 설치가 사고를 낸다.
	/// 그래서 "어느 쪽이 옳다"가 아니라 *모드로 분리*한다.
	/// </summary>
	public enum PlacementInputMode
	{
		/// <summary> 누르고 있는 동안 계속 설치(드래그로 죽 긋기). 월드 건설 기본값 — 기존 동작. </summary>
		Continuous = 0,

		/// <summary> 한 번 누를 때 한 개만. 비용이 붙는 배치(개척 포탑·채집 인형)에 필요. </summary>
		SingleClick = 1,
	}
}
