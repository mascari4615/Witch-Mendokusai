        public static string Get(string english)
        {
            string translated;
            return KarmoEditorLocalization.CurrentLanguage == KarmoEditorLocalization.Language.Korean && KOREAN.TryGetValue(english, out translated) ? translated : english;
        }

        public static string Format(string english, params object[] arguments)
        {
            CultureInfo culture = CultureInfo.GetCultureInfo(KarmoEditorLocalization.CurrentLanguage == KarmoEditorLocalization.Language.Korean ? "ko-KR" : "en-US");
            return string.Format(culture, Get(english), arguments);
        }

        public static string[] Labels(string[] values)
        {
            return Array.ConvertAll(values, NodeLabel);
        }

        public static string NodeLabel(string value)
        {
            int separator = value.LastIndexOf('/');
            if (separator >= 0) return value.Substring(0, separator + 1) + Get(value.Substring(separator + 1));
            if (value.StartsWith("Actor ", StringComparison.Ordinal)) return Format("Actor {0}", value.Substring(6));
            return Get(value);
        }
